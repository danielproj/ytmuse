    let entry = try QueueEntry(id: UUID(uuidString: "00000000-0000-0000-0000-000000000010")!, media: ServiceID("old"), segment: .user, originalOrder: 0)
    return try QueueSession(account: request.account!, version: 1, entries: [entry], currentOccurrence: entry.id, position: 7, shuffleSeed: 42, repeatMode: .one, autoplay: true)
}
func mutation(_ request: RequestContext, id: UUID = UUID(), title: String = "synthetic-playlist") throws -> PendingMutation {
    try PendingMutation(id: id, account: request.account!, target: ServiceID("playlist"), intent: .playlist(.create(title: title, privacy: .private)), precondition: .init(providerVersion: "version-one", snapshotVersion: UInt64.max), outcome: .pending(id))
}
