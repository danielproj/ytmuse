func context(channel: String = "synthetic-channel", account: String = "00000000-0000-0000-0000-000000000001", region: String = "US", generation: UInt64 = 1) throws -> RequestContext {
    try RequestContext(account: AccountContext(accountID: UUID(uuidString: account)!, channelID: ID<ChannelTag>(channel), region: region), accountGeneration: generation, requestGeneration: 1)
}
func disposable() throws -> URL {
    let directory = FileManager.default.temporaryDirectory.appendingPathComponent("native-music-T03-" + UUID().uuidString)
    try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: false, attributes: [.posixPermissions: 0o700])
    return directory
}
func register(_ store: SQLiteStore, _ request: RequestContext) async throws {
    let account = request.account!
    try await store.saveAccount(Account(id: account.accountID, serviceIdentity: ServiceID("synthetic-service"), context: account, displayName: "Synthetic identity", credential: CredentialReference("00000000-0000-0000-0000-000000000099")), context: request)
}
func media(_ id: String, title: String = "Synthetic melody") throws -> MediaItem {
    try MediaItem(id: ServiceID(id), kind: .song, title: title, artists: [ServiceID("artist")], duration: 180, artwork: [ServiceID("artwork")], explicit: false, availability: .available)
}
