    // MARK: partial key cleanup
    @Test func aKeyCleanupThatFailsHalfwayIsRetriedAndNeverLeavesOrCrossesAccounts() async throws {
        let rig = try await DeletionRig(); defer { rig.cleanup() }
        try await rig.lifecycle.switchIdentity(to: rig.a.context)
        let target = rig.root.appendingPathComponent("accounts").appendingPathComponent(PrivateAccountFiles.relativePath(rig.a.context))
