        let bRecords = await rig.vault.records(for: rig.b.context)
        await rig.vault.setPartialFailures(1)
        do { try await rig.lifecycle.remove(rig.a.context); Issue.record("a partial key cleanup reported success") }
        catch { #expect(error as? LifecycleError == .cleanupFailed(["keychain"]), "\(error)") }
        // Half-deleted: some of A's records remain, the removal is pending, A cannot be used, and nothing else was touched.
        #expect(await rig.vault.records(for: rig.a.context) == 1, "the failed deletion left exactly the record it could not remove")
        let pending = await rig.lifecycle.snapshot()
        #expect(pending.directory.identities.first { $0.id == rig.a.context }?.state == .removalPending)
        #expect(pending.context.account == nil, "no fallback to the other account while the removal is pending")
        await #expect(throws: LifecycleError.removalPending) { try await rig.lifecycle.switchIdentity(to: rig.a.context) }
        await #expect(throws: LifecycleError.removalPending) { _ = try await rig.lifecycle.beginAuthentication(for: rig.a.context) }
        #expect(!FileManager.default.fileExists(atPath: target.path), "the other participants finished their cleanup")
        #expect(await rig.vault.records(for: rig.b.context) == bRecords, "B's keys are untouched")
        // The stored roster, not a fake that nothing writes to: A is recorded as "removal pending" and B is still there.
        let stored = try await rig.roster.load()
        #expect(stored.identities.first { $0.id == rig.a.context }?.state == .removalPending && stored.identities.contains { $0.id == rig.b.context }, "the stored roster holds the pending removal and the other account")
        // The retry (a second Remove, or the next launch) finishes it.
        try await rig.lifecycle.remove(rig.a.context)
        #expect(await rig.vault.records(for: rig.a.context) == 0)
        #expect(await rig.lifecycle.snapshot().directory.identities.map(\.id) == [rig.b.context])
        #expect(await rig.vault.records(for: rig.b.context) == bRecords)
        // A relaunch with the removal still pending (the process ended before the retry) resumes it from the stored roster, again without a fallback.
        let second = try await DeletionRig(); defer { second.cleanup() }
        await second.vault.setPartialFailures(1)
        try? await second.lifecycle.remove(second.a.context)
        let relaunched = try await AccountLifecycle.open(vault: second.vault, store: second.roster, participants: [ScopedAccountWork()])
        let state = await relaunched.snapshot()
        #expect(state.directory.identities.first { $0.id == second.a.context }?.state == .removalPending, "the pending removal survives a relaunch")
        #expect(state.context.account == nil)
        try await relaunched.remove(second.a.context)
        #expect(await second.vault.records(for: second.a.context) == 0)
    }

