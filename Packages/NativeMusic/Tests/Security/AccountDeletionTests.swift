/// A download source that serves generated bytes and can hold a read until released (optionally ignoring cancellation, as a slow network does).
actor HoldingSource: DownloadSource {
    private var held: [UUID: CheckedContinuation<Void, Never>] = [:]
    private(set) var blocked = 0
    private(set) var calls = 0
    var hold = false
    var ignoreCancellation = false
    let bytes = Data((0..<8192).map { UInt8(truncatingIfNeeded: $0 &* 31) })
    func setHold(_ value: Bool, ignoringCancellation: Bool = false) { hold = value; ignoreCancellation = ignoringCancellation }
    func release() { hold = false; let all = held; held = [:]; for c in all.values { c.resume() } }
    private func wake(_ id: UUID) { held.removeValue(forKey: id)?.resume() }
    func waitUntilBlocked() async { let deadline = ContinuousClock.now + .seconds(5); while blocked == 0, ContinuousClock.now < deadline { try? await Task.sleep(for: .milliseconds(2)) } }
    func describe(item: SourceItem, context: RequestContext) async throws -> SourceDescriptor {
        calls += 1
        let now = Date()
        return SourceDescriptor(variant: "v-" + item.media.rawValue, validator: "v1", length: Int64(bytes.count), supportsRanges: true, urlExpiresAt: now.addingTimeInterval(60), sha256: nil,
                                permission: DownloadPermission(issuer: "Owned synthetic", sourceEncryption: "none", validatedAt: now, expires: now.addingTimeInterval(3600), renewAfter: nil, renewalReference: "r"))
    }
    func read(item: SourceItem, descriptor: SourceDescriptor, offset: Int64, count: Int, context: RequestContext) async throws -> SourceRead {
        calls += 1
        if hold {
            blocked += 1
            let id = UUID()
            if ignoreCancellation { await withCheckedContinuation { held[id] = $0 } }
            else { await withTaskCancellationHandler { await withCheckedContinuation { held[id] = $0 } } onCancel: { Task { await self.wake(id) } } }
            blocked -= 1
            if !ignoreCancellation { try Task.checkCancellation() }
        }
        let end = min(Int(offset) + count, bytes.count)
        guard offset < Int64(bytes.count) else { return SourceRead(data: Data(), endOfStream: true) }
        return SourceRead(data: bytes.subdata(in: Int(offset)..<end), endOfStream: end >= bytes.count)
    }
    func renew(item: SourceItem, descriptor: SourceDescriptor, context: RequestContext) async throws -> DownloadPermission { throw SourceFailure.permissionDenied }
    func contentDigest(item: SourceItem, descriptor: SourceDescriptor, length: Int64) async throws -> String? { nil }
}
actor MemoryRetention: RetentionSink {
    private(set) var objects: [String: Data] = [:]
    private(set) var references: [String: Set<String>] = [:]
    func retain(file: URL, variant: String, grant: RetentionGrant, reference: String, context: RequestContext) throws { objects[variant] = try Data(contentsOf: file); references[variant, default: []].insert(reference) }
    func addReference(variant: String, reference: String, context: RequestContext) { references[variant, default: []].insert(reference) }
    func removeReference(variant: String, reference: String, context: RequestContext) { references[variant]?.remove(reference); if references[variant]?.isEmpty == true { objects[variant] = nil; references[variant] = nil } }
    func setPinned(variant: String, pinned: Bool, context: RequestContext) {}
    func retainedLength(variant: String, context: RequestContext) throws -> Int { guard let o = objects[variant] else { throw OfflineRecovery.notRetained }; return o.count }
    func verify(variant: String, context: RequestContext) throws -> String? { nil }
    func updateGrant(variant: String, grant: RetentionGrant, context: RequestContext) {}
    func delete(variant: String, context: RequestContext) { objects[variant] = nil; references[variant] = nil }
    func bind(_ context: RequestContext) {}
}
