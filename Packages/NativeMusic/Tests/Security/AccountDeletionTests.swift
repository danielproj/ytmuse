// T29.4. An account is removed while work is in flight: a download mid-transfer, outbox writes, a Spotlight index run, a widget snapshot flush, and a key cleanup that fails
// halfway. Each case must finish or retry safely, must never fall back to another account, and must never delete anything remotely. Every store here is an in-memory fake or a
// scratch directory, and the vault is a fake: no Keychain item (real or test) is touched.

/// A vault in memory, with the failures a real one has: a partial deletion that removes some records and then fails.
actor FakeVault: SessionVault {
    private var records: [CredentialReference: (account: AccountContext, bytes: Data)] = [:]
    private var bound: RequestContext?
    private(set) var deleteAllCalls = 0
    /// The next `n` deleteAll calls remove all but one record of the account and then throw.
    var partialFailures = 0
    func setPartialFailures(_ n: Int) { partialFailures = n }
    func records(for account: AccountContext) -> Int { records.values.filter { $0.account == account }.count }
    var total: Int { records.count }
    func bind(_ context: RequestContext) { bound = context }
    func insert(_ bytes: Data, for account: AccountContext) throws -> CredentialReference {
        let reference = try CredentialReference(UUID().uuidString); records[reference] = (account, bytes)
        // A second record under the same account stands for a multi-record credential (session + rotation), so a partial cleanup has something to leave behind.
        records[try CredentialReference(UUID().uuidString)] = (account, bytes)
        return reference
    }
    func read(_ reference: CredentialReference, context: RequestContext) throws -> Data {
        guard let record = records[reference], context.account == record.account else { throw LifecycleError.keychain(-25300) }
        return record.bytes
    }
    func delete(_ reference: CredentialReference, for account: AccountContext) throws { guard records[reference]?.account == account else { return }; records[reference] = nil }
    func deleteAll(for account: AccountContext) throws {
        deleteAllCalls += 1
        let mine = records.filter { $0.value.account == account }.map(\.key)
        if partialFailures > 0 {
            partialFailures -= 1
            for key in mine.dropLast() { records[key] = nil }
            throw LifecycleError.keychain(-25293)
        }
        for key in mine { records[key] = nil }
    }
    func replace(_ reference: CredentialReference, with bytes: Data, context: RequestContext) throws {
        guard let record = records[reference], context.account == record.account else { throw LifecycleError.keychain(-25300) }
        records[reference] = (record.account, bytes)
    }
}
