actor ScopeGate {
    private let scope: IntentScope
    private var waiter: CheckedContinuation<Void, Never>?
    private var reading = false
    init(_ scope: IntentScope) { self.scope = scope }
    func read() async -> IntentScope? {
        if !gateOpen { reading = true; await withCheckedContinuation { waiter = $0 } }
        return scope
    }
    private var gateOpen = false
    func waitUntilReading() async { let deadline = ContinuousClock.now + .seconds(5); while !reading, ContinuousClock.now < deadline { try? await Task.sleep(for: .milliseconds(2)) } }
    func release() { gateOpen = true; waiter?.resume(); waiter = nil }
}
/// An index backend whose `index` call can be held, like the system's index under load.
final class GatedIndex: SearchableIndexBackend, @unchecked Sendable {
    private let inner = InMemorySearchableIndex()
    private let lock = NSLock()
    private var gate = false
    private var blocked = false
    private var waiting: [CheckedContinuation<Void, Never>] = []
    var entries: [SpotlightEntry] { inner.entries }
    func setGate(_ on: Bool) async {
        let toResume: [CheckedContinuation<Void, Never>] = lock.withLock { gate = on; if on { return [] }; let w = waiting; waiting = []; return w }
        for c in toResume { c.resume() }
    }
    func waitUntilBlocked() async { let deadline = ContinuousClock.now + .seconds(5); while !lock.withLock({ blocked }), ContinuousClock.now < deadline { try? await Task.sleep(for: .milliseconds(2)) } }
    func index(_ entries: [SpotlightEntry], domain: String) async throws {
        let held = lock.withLock { gate }
        if held { lock.withLock { blocked = true }; await withCheckedContinuation { c in lock.withLock { waiting.append(c) } } }
        try await inner.index(entries, domain: domain)
    }
    func delete(uniqueIDs: [String]) async throws { try await inner.delete(uniqueIDs: uniqueIDs) }
    func delete(domains: [String]) async throws { try await inner.delete(domains: domains) }
}
