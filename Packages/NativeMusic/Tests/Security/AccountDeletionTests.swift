/// Everything one account-removal scenario needs, composed the way the product composes it (roster, SQLite, private files, scoped work, downloads).
final class DeletionRig: @unchecked Sendable {
    let root: URL, store: SQLiteStore, roster: SQLiteAccountDirectory, vault = FakeVault(), directory = RosterStore()
    let source = HoldingSource(), retention = MemoryRetention()
    let scheduler: DownloadScheduler, files: PrivateAccountFiles, lifecycle: AccountLifecycle
    let a: Account, b: Account
    var ledgerRoot: URL { root.appendingPathComponent("jobs", isDirectory: true) }
    init() async throws {
        root = FileManager.default.temporaryDirectory.appendingPathComponent("ytmuse-w29-del-" + UUID().uuidString, isDirectory: true)
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        let initial = RequestContext(account: nil, accountGeneration: 0, requestGeneration: 0)
        store = try SQLiteStore(directory: root.appendingPathComponent("database"), context: initial)
        roster = SQLiteAccountDirectory(store: store, context: initial)
        let storage = SQLiteAccountParticipant(store: store, directory: roster)
        files = try PrivateAccountFiles(id: "private-files", root: root.appendingPathComponent("accounts"))
        scheduler = try DownloadScheduler(ledgerRoot: root.appendingPathComponent("jobs", isDirectory: true), sink: retention, sources: [.owned: source], wall: SystemWallClock(), volume: VolumeStub(),
                                          configuration: .init(chunkBytes: 1024, persistEveryChunks: 1, minimumBudget: 1024), wake: { _, _ in { } }, suggestionsAvailable: true,
                                          originOf: { $0.rawValue.hasPrefix("owned-") ? .owned : MediaOrigin.classify($0) })
        a = try syntheticAccount("w29-a"); b = try syntheticAccount("w29-b")
        lifecycle = try await AccountLifecycle.open(vault: vault, store: roster, participants: [ScopedAccountWork(), storage, files, scheduler])
        try await connect(lifecycle, a); try await connect(lifecycle, b)
    }
    func cleanup() { try? FileManager.default.removeItem(at: root) }
    var context: RequestContext { get async { await lifecycle.snapshot().context } }
    func tree(_ url: URL) -> [String] {
        guard let walker = FileManager.default.enumerator(at: url, includingPropertiesForKeys: nil) else { return [] }
        return walker.compactMap { ($0 as? URL)?.path.replacingOccurrences(of: url.path, with: "") }.sorted()
    }
    /// Regular files under `url` by relative path, with their content digests (directories are not content).
    func files(_ url: URL) -> [String: Int] {
        var out: [String: Int] = [:]
        guard let walker = FileManager.default.enumerator(at: url, includingPropertiesForKeys: [.isRegularFileKey]) else { return out }
        for case let file as URL in walker where (try? file.resourceValues(forKeys: [.isRegularFileKey]).isRegularFile) == true {
            out[file.path.replacingOccurrences(of: url.path, with: "")] = (try? Data(contentsOf: file))?.hashValue ?? -1
        }
        return out
    }
    func waitAvailable(_ media: ServiceID) async -> Bool {
        for _ in 0..<500 { if await scheduler.isAvailable(media) { return true }; try? await Task.sleep(for: .milliseconds(10)) }
        return false
    }
    func mutation(for account: Account, context: RequestContext, title: String) throws -> PendingMutation {
        let id = UUID()
        return try PendingMutation(id: id, account: account.context, target: ServiceID("playlist"), intent: .playlist(.create(title: title, privacy: .private)), precondition: .init(providerVersion: "v", snapshotVersion: UInt64.max), outcome: .pending(id))
    }
}

@Suite("T29.4 an account is removed while work is in flight", .serialized) struct AccountDeletionTests {
    // MARK: downloads
    @Test(arguments: [false, true]) func removingTheAccountMidDownloadLeavesNothingOfItAndTouchesNoOtherAccount(sourceIgnoresCancellation: Bool) async throws {
        let rig = try await DeletionRig(); defer { rig.cleanup() }
        // B keeps one finished download; it must survive A's removal untouched.
        try await rig.lifecycle.switchIdentity(to: rig.b.context)
        let keep = try ServiceID("owned-keep")
        _ = await rig.scheduler.download(keep, title: "Kept", request: .manual)
        #expect(await rig.waitAvailable(keep), "B's download finished")
        #expect(!rig.tree(rig.ledgerRoot).isEmpty)
        // A starts a download that stalls mid-transfer.
        let bDirectories = Set(rig.files(rig.ledgerRoot).keys.map { String($0.split(separator: "/").prefix(2).joined(separator: "/")) })
        try await rig.lifecycle.switchIdentity(to: rig.a.context)
        let treeBeforeA = Set(rig.tree(rig.ledgerRoot))
        // B's files as they stand once the scheduler has moved off B (its own detach may settle B's ledger); A's empty ledger, created by the switch, is not B's.
        let bFiles = rig.files(rig.ledgerRoot).filter { entry in bDirectories.contains(where: { dir in entry.key.hasPrefix(dir.hasPrefix("/") ? dir : "/" + dir) }) }
        #expect(bFiles.keys.contains { $0.hasSuffix("ledger.json") }, "B's ledger is on disk")
        await rig.source.setHold(true, ignoringCancellation: sourceIgnoresCancellation)
        let doomed = try ServiceID("owned-doomed")
        _ = await rig.scheduler.download(doomed, title: "Doomed", request: .manual)
        await rig.source.waitUntilBlocked()
        #expect(await rig.source.blocked >= 1, "the transfer is genuinely mid-flight")
        let inFlight = Set(rig.tree(rig.ledgerRoot)).subtracting(treeBeforeA)
        #expect(!inFlight.isEmpty, "A's ledger and staging exist on disk before the removal: \(inFlight)")
        // The removal runs while the read is held; a source that ignores cancellation is released shortly after, as a slow network eventually is.
        let removal = Task { try await rig.lifecycle.remove(rig.a.context) }
        if sourceIgnoresCancellation { try await Task.sleep(for: .milliseconds(50)); await rig.source.release() }
        try await removal.value
        await rig.source.release()
        // Nothing of A is left, B's tree is exactly what it was, and the active account did not fall back to B.
        let after = rig.tree(rig.ledgerRoot)
        #expect(Set(after).isDisjoint(with: inFlight), "A's ledger, jobs and staging are gone: \(Set(after).intersection(inFlight))")
        let bAfter = rig.files(rig.ledgerRoot)
        #expect(bAfter == bFiles, "B's ledger and usage files are byte for byte what they were, and nothing else remains")
        let snapshot = await rig.lifecycle.snapshot()
        #expect(snapshot.context.account == nil, "no account becomes active when the active one is removed")
        #expect(await rig.scheduler.isAvailable(doomed) == false)
        let aKeys = await rig.vault.records(for: rig.a.context), bKeys = await rig.vault.records(for: rig.b.context)
        #expect(aKeys == 0 && bKeys > 0, "A's keys are erased and B's are not")
        #expect(snapshot.directory.identities.map(\.id) == [rig.b.context])
        // A late chunk delivered after removal cannot write: the source is released and the retention sink holds nothing for A.
        try await Task.sleep(for: .milliseconds(50))
        #expect(await rig.retention.objects.keys.contains("v-owned-doomed") == false)
        #expect(Set(rig.tree(rig.ledgerRoot)).isDisjoint(with: inFlight), "no late write recreated A's files")
    }

    // MARK: outbox
    @Test func outboxWritesRacingTheRemovalAreRefusedAfterItAndNothingIsSentRemotely() async throws {
        let rig = try await DeletionRig(); defer { rig.cleanup() }
        try await rig.lifecycle.switchIdentity(to: rig.b.context)
        let bContext = await rig.context
        let bMutation = try rig.mutation(for: rig.b, context: bContext, title: "b-keeps-this")
        _ = try await rig.store.enqueue(bMutation, context: bContext).outcome.get()
        try await rig.lifecycle.switchIdentity(to: rig.a.context)
        let aContext = await rig.context
        let sends = Counter()
        let executor = DurableMutationExecutor(outbox: rig.store)
        var queued: [PendingMutation] = []
        for i in 0..<5 { let m = try rig.mutation(for: rig.a, context: aContext, title: "a-\(i)"); queued.append(m); _ = try await rig.store.enqueue(m, context: aContext).outcome.get() }
        // A writer keeps enqueuing for A while the account is removed.
        let writer = Task { () -> (accepted: Int, refused: Int) in
            var accepted = 0, refused = 0
            for i in 0..<300 {
                guard let m = try? rig.mutation(for: rig.a, context: aContext, title: "late-\(i)") else { continue }
                switch await rig.store.enqueue(m, context: aContext).outcome { case .success: accepted += 1; case .failure: refused += 1 }
                if i % 8 == 0 { await Task.yield() }
            }
            return (accepted, refused)
        }
        try await Task.sleep(for: .milliseconds(2))
        try await rig.lifecycle.remove(rig.a.context)
        let result = await writer.value
        #expect(result.refused > 0, "writes after the removal barrier are refused (accepted \(result.accepted), refused \(result.refused))")
        // A pending operation of the removed account is never submitted: its context is stale.
        let outcome = await executor.execute(id: queued[0].id, context: aContext) { _ in sends.bump(); return .confirmed }
        if case .success = outcome.outcome { Issue.record("a removed account's operation was executed") }
        #expect(sends.value == 0, "nothing is sent for a removed account")
        // Reopened from disk (a restart): A's operations are gone, and B's survive and are readable once B is active.
        await rig.store.close()
        let reopened = try SQLiteStore(directory: rig.root.appendingPathComponent("database"), context: RequestContext(account: nil, accountGeneration: 100, requestGeneration: 0))
        let roster = SQLiteAccountDirectory(store: reopened, context: RequestContext(account: nil, accountGeneration: 100, requestGeneration: 0))
        let identities = try await roster.load().identities.map(\.id)
        #expect(identities == [rig.b.context], "the removed account is not in the stored roster after a restart")
        // TH2 (W29 L5): the comment above says A's operations are gone, so the outbox itself is read, not only the roster. B's one operation is the control: the same read finds it.
        let bAfterRestart = RequestContext(account: bContext.account, accountGeneration: 101, requestGeneration: 0)
        let aAfterRestart = RequestContext(account: aContext.account, accountGeneration: 102, requestGeneration: 0)
        await reopened.bind(bAfterRestart)
        #expect(try await reopened.pendingMutations(context: bAfterRestart).map(\.id) == [bMutation.id], "B's operation survived the restart (control: the read does find an account's rows)")
        await reopened.bind(aAfterRestart)
        let leftOfA = try await reopened.pendingMutations(context: aAfterRestart)
        #expect(leftOfA.isEmpty, "none of A's \(queued.count + result.accepted) accepted operations is in the outbox after a restart: \(leftOfA.count) left")
        #expect(queued.count + result.accepted >= 5, "the removal had something to remove")
        await reopened.close()
    }

